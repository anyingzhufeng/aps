-- ============================================================
-- 092 sch_schedule_result_detail（排程结果明细表）
-- APS排程引擎生成的车间级排程结果，包含每个工序的
-- 详细排程时间、设备、班组及状态信息。
-- 创建时间: 2026-05-07
-- ============================================================

DROP TABLE IF EXISTS sch_schedule_result_detail;

CREATE TABLE sch_schedule_result_detail (
    detail_id              VARCHAR(36)  NOT NULL COMMENT '明细主键UUID',
    schedule_id             VARCHAR(36)  NOT NULL COMMENT '归属排程结果ID（sch_schedule_result.schedule_id）',
    result_id               VARCHAR(36)  NOT NULL COMMENT '排程方案ID（sch_schedule_result.result_id）',
    workshop_code           VARCHAR(20)  NOT NULL COMMENT '车间编码',
    workcenter_code         VARCHAR(20)  NULL COMMENT '工序车间编码',
    machine_code            VARCHAR(20)  NULL COMMENT '设备编码',
    skill_code              VARCHAR(20)  NULL COMMENT '技能编码',
    calendar_date           DATE         NOT NULL COMMENT '日历日期',
    shift_code              VARCHAR(20)  NULL COMMENT '班次编码',
    work_order_no           VARCHAR(36)  NOT NULL COMMENT '工单编号',
    operation_seq           INT          NOT NULL COMMENT '工序序号',
    operation_code          VARCHAR(50)  NULL COMMENT '工序编码',
    operation_name          VARCHAR(100) NULL COMMENT '工序名称',
    planned_start           DATETIME     NOT NULL COMMENT '计划开始时间',
    planned_end             DATETIME     NOT NULL COMMENT '计划结束时间',
    planned_duration_min    INT          NOT NULL COMMENT '计划时长（分钟）',
    planned_qty             DECIMAL(18,6) NULL COMMENT '计划数量',
    actual_start            DATETIME     NULL COMMENT '实际开始时间',
    actual_end              DATETIME     NULL COMMENT '实际结束时间',
    actual_qty              DECIMAL(18,6) NULL COMMENT '实际完成数量',
    setup_minutes           INT          NULL COMMENT '换型时间（分钟）',
    run_minutes             INT          NULL COMMENT '加工时间（分钟）',
    queue_minutes           INT          NULL COMMENT '排队等待时间（分钟）',
    travel_minutes          INT          NULL COMMENT '转移时间（分钟）',
    worker_code             VARCHAR(20)  NULL COMMENT '作业人员编码',
    team_code               VARCHAR(20)  NULL COMMENT '班组编码',
    priority_score          INT          NULL COMMENT '优先级评分',
    is_frozen               TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '是否冻结（1=冻结，0=不冻结）',
    is_locked               TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '是否锁定（1=锁定，0=不锁定）',
    is_split                TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '是否拆分（1=拆分，0=未拆分）',
    split_group_id          VARCHAR(36)  NULL COMMENT '拆分组ID（同一批次拆分的工序共享）',
    shortage_flag           TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '缺料标志（1=缺料，0=正常）',
    shortage_material_code  VARCHAR(50)  NULL COMMENT '缺料物料编码',
    shortage_qty            DECIMAL(18,6) NULL COMMENT '缺料数量',
    alternate_machine_flag  TINYINT(1)  NOT NULL DEFAULT 0 COMMENT '是否使用替代设备',
    alternate_source        VARCHAR(50)  NULL COMMENT '替代来源说明',
    setup_type               VARCHAR(20)  NULL COMMENT '换型类型：product_change/color_change/tool_change',
    material_lot             VARCHAR(50)  NULL COMMENT '物料批次',
    unit_cost               DECIMAL(12,4) NULL COMMENT '单位加工成本',
    overtime_type           VARCHAR(10)  NULL COMMENT '加班类型：normal/overtime/weekend/holiday',
    utilization_rate        DECIMAL(5,2)  NULL COMMENT '设备利用率（%）',
    delay_minutes           INT          NULL COMMENT '延迟时间（分钟）',
    delay_reason             VARCHAR(200) NULL COMMENT '延迟原因',
    release_time            DATETIME     NULL COMMENT '工单释放时间',
    due_date                DATETIME     NULL COMMENT '工单截止时间',
    is_critical_path        TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '是否关键路径（1=关键，0=非关键）',
    criticality_score       INT          NULL COMMENT '关键度评分（1-100）',
    schedule_status         VARCHAR(20)  NOT NULL DEFAULT 'SCHEDULED' COMMENT '排程状态：SCHEDULED/DISPATCHED/IN_PROGRESS/COMPLETED/DELAYED/CANCELLED',
    gantt_row               INT          NULL COMMENT '甘特图行号',
    gantt_color             VARCHAR(20)  NULL COMMENT '甘特图颜色标识',
    remarks                 VARCHAR(500) NULL COMMENT '备注',
    created_at              DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    updated_at              DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    created_by              VARCHAR(36)  NULL COMMENT '创建人',
    updated_by              VARCHAR(36)  NULL COMMENT '更新人',
    PRIMARY KEY (detail_id),
    KEY idx_schedule_id (schedule_id),
    KEY idx_result_id (result_id),
    KEY idx_work_order_no (work_order_no),
    KEY idx_workshop_date (workshop_code, calendar_date),
    KEY idx_machine_date (machine_code, calendar_date),
    KEY idx_status (schedule_status),
    KEY idx_is_frozen (is_frozen),
    KEY idx_is_locked (is_locked),
    KEY idx_critical_path (is_critical_path),
    KEY idx_shortage (shortage_flag)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='排程结果明细表';
